package manifest

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

type RenderOptions struct {
	ManifestPath      string
	IncludeReferences bool
}

func RenderSystemd(effective Effective, options RenderOptions) (string, error) {
	deployment := effective.Document.Deployment
	serviceName := "serenox"
	user := "serenox"
	working := effective.Runtime.DataDir
	if deployment != nil {
		if deployment.ServiceName != "" {
			serviceName = deployment.ServiceName
		}
		if deployment.User != "" {
			user = deployment.User
		}
		if deployment.WorkingDirectory != "" {
			working = deployment.WorkingDirectory
		}
	}
	path := options.ManifestPath
	if path == "" {
		path = effective.ManifestPath
	}
	lines := []string{
		"[Unit]", "Description=Serenox " + systemdValue(serviceName), "After=network-online.target", "Wants=network-online.target", "", "[Service]",
		"Type=simple", "User=" + systemdValue(user), "WorkingDirectory=" + systemdValue(working),
		"ExecStart=serenox run --manifest " + systemdValue(path), "Restart=on-failure", "RestartSec=5s",
		"TimeoutStopSec=" + effective.Runtime.ShutdownTimeout.String(), "ReadWritePaths=" + systemdValue(effective.Runtime.DataDir),
	}
	if deployment != nil && deployment.EnvironmentFile != "" {
		lines = append(lines, "EnvironmentFile=-"+systemdValue(deployment.EnvironmentFile))
	}
	if options.IncludeReferences {
		for _, name := range secretNames(effective.Document) {
			lines = append(lines, "# secret reference: "+name)
		}
	}
	lines = append(lines, "", "[Install]", "WantedBy=multi-user.target", "")
	return strings.Join(lines, "\n"), nil
}

func RenderCompose(effective Effective, options RenderOptions) (string, error) {
	project := "serenox"
	image := "serenox:local"
	if effective.Document.Deployment != nil {
		if effective.Document.Deployment.ComposeProject != "" {
			project = effective.Document.Deployment.ComposeProject
		}
		if effective.Document.Deployment.Image != "" {
			image = effective.Document.Deployment.Image
		}
	}
	var builder strings.Builder
	fmt.Fprintf(&builder, "# generated by Serenox; project: %s\nservices:\n  serenox:\n    image: %s\n    command: [\"run\", \"--manifest\", \"/etc/serenox/serenox.yaml\"]\n    restart: unless-stopped\n    working_dir: /var/lib/serenox\n    volumes:\n      - serenox-data:/var/lib/serenox\n      - ./serenox.yaml:/etc/serenox/serenox.yaml:ro\n    healthcheck:\n      test: [\"CMD\", \"serenox\", \"manifest\", \"check\", \"--file\", \"/etc/serenox/serenox.yaml\"]\n      interval: 30s\n      timeout: 5s\n      retries: 3\n", project, yamlSafe(image))
	names := make([]string, 0, len(effective.Document.Services))
	for name := range effective.Document.Services {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		service := effective.Document.Services[name]
		switch service.Kind {
		case "postgres":
			builder.WriteString("  " + name + ":\n    image: postgres:16\n    environment:\n      POSTGRES_USER: serenox\n      POSTGRES_PASSWORD_FILE: /run/secrets/serenox_db_password\n    volumes:\n      - " + name + "-data:/var/lib/postgresql/data\n    secrets:\n      - serenox_db_password\n")
		case "redis":
			builder.WriteString("  " + name + ":\n    image: redis:7\n    command: [\"redis-server\", \"--appendonly\", \"yes\"]\n    volumes:\n      - " + name + "-data:/data\n")
		case "object_storage":
			builder.WriteString("  " + name + ":\n    image: minio/minio:latest\n    command: [\"server\", \"/data\"]\n    volumes:\n      - " + name + "-data:/data\n")
		}
	}
	builder.WriteString("volumes:\n  serenox-data:\n")
	for _, name := range names {
		builder.WriteString("  " + name + "-data:\n")
	}
	if options.IncludeReferences {
		builder.WriteString("secrets:\n  serenox_db_password:\n    environment: SERENOX_POSTGRES_PASSWORD\n")
	}
	return builder.String(), nil
}

func systemdValue(value string) string {
	value = strings.ReplaceAll(value, "%", "%%")
	value = strings.ReplaceAll(value, "\n", "")
	return value
}

func yamlSafe(value string) string {
	return strings.ReplaceAll(strings.ReplaceAll(value, "\n", ""), "\"", "\\\"")
}

func secretNames(doc Document) []string {
	result := make([]string, 0, 2)
	if doc.Telegram.APIID.Ref.Env() != "" {
		result = append(result, doc.Telegram.APIID.Ref.Env())
	}
	if doc.Telegram.APIHash.Env() != "" {
		result = append(result, doc.Telegram.APIHash.Env())
	}
	if doc.Telegram.APIHash.File() != "" {
		result = append(result, filepath.ToSlash(doc.Telegram.APIHash.File()))
	}
	sort.Strings(result)
	return result
}

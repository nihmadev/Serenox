#!/usr/bin/env bash
set -euo pipefail

# This is deliberately a boundary test, not a native Telegram build. It copies
# only the Go source needed by the selected packages, removes the concrete gotd
# adapter, and supplies its public package shape so auth CLI/bootstrap/session
# behavior can be tested on memory-constrained contributor machines.

ROOT_DIR="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
TMP_PARENT="${TMPDIR:-/tmp}"
TEMP_DIR="$(mktemp -d "${TMP_PARENT%/}/serenox-auth-boundary.XXXXXX")"

cleanup() {
	case "$TEMP_DIR" in
		"${TMP_PARENT%/}"/serenox-auth-boundary.*) rm -rf -- "$TEMP_DIR" ;;
		*) printf 'refusing to remove unexpected temporary path: %s\n' "$TEMP_DIR" >&2 ;;
	esac
}
trap cleanup EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

printf '%s\n' 'AUTH BOUNDARY ONLY: the concrete gotd adapter is excluded and is not compiled.'

tar -C "$ROOT_DIR" -cf - go.mod go.sum cmd internal pkg | tar -C "$TEMP_DIR" -xf -

rm -f -- \
	"$TEMP_DIR/internal/telegram/auth.go" \
	"$TEMP_DIR/internal/telegram/gotd_actions.go" \
	"$TEMP_DIR/internal/telegram/gotd_convert.go" \
	"$TEMP_DIR/internal/telegram/gotd_session.go" \
	"$TEMP_DIR/internal/telegram/live.go" \
	"$TEMP_DIR/internal/telegram/live_test.go" \
	"$TEMP_DIR/internal/telegram/peers.go"

cat >"$TEMP_DIR/internal/telegram/live_boundary_stub.go" <<'EOF'
// Code generated by scripts/test-auth-boundary.sh for an isolated test copy.
// It preserves package boundaries only; it is not a native Telegram adapter.
package telegram

import (
	"context"
	"errors"
	"time"

	pluginv1 "github.com/nihmadev/Serenox/pkg/pluginproto/v1"
)

var (
	ErrAuthPromptRequired = errors.New("Telegram session is not authorized; an authentication prompt is required")
	ErrNotAuthorized      = errors.New("Telegram session is not authorized; run authorization before starting live transport")
	errNativeBoundary     = errors.New("native gotd adapter is excluded from the auth boundary test")
)

type CodePrompt struct {
	Delivery string
	Length   int
	Timeout  time.Duration
}

type Prompt interface {
	Phone(context.Context) (string, error)
	Code(context.Context, CodePrompt) (string, error)
	Password(context.Context) (string, error)
}

type Identity struct {
	UserID   int64
	Username string
}

type DeviceInfo struct {
	DeviceModel    string
	SystemVersion  string
	AppVersion     string
	SystemLangCode string
	LangCode       string
}

type LiveConfig struct {
	AppID             int
	AppHash           string
	Session           SessionStore
	UpdateCapacity    int
	PeerCacheCapacity int
	Device            DeviceInfo
}

type LiveTransport struct{}

func Authorize(context.Context, LiveConfig, Prompt) (Identity, error) {
	return Identity{}, errNativeBoundary
}

func NewLive(LiveConfig) (*LiveTransport, error) {
	return nil, errNativeBoundary
}

func (*LiveTransport) Run(context.Context, Sink) error {
	return errNativeBoundary
}

func (*LiveTransport) Apply(context.Context, pluginv1.Action) (pluginv1.ActionResult, error) {
	return pluginv1.ActionResult{}, errNativeBoundary
}

func (*LiveTransport) Close(context.Context) error {
	return nil
}

var _ Transport = (*LiveTransport)(nil)
EOF

cd "$TEMP_DIR"
GOTOOLCHAIN=local \
	GOCACHE="$ROOT_DIR/.cache/go-build" \
	GOMAXPROCS=1 \
	GOTRACEBACK=none \
	go test -p=1 \
		./internal/telegram \
		./internal/bootstrap \
		./cmd/serenox \
		./cmd/serenoxd

printf '%s\n' 'AUTH BOUNDARY PASS: CLI/bootstrap/session tests passed; native gotd compilation was not attempted.'
